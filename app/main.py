"""FastAPI routes - the public REST API in front of the Urja Meter Ops portal.

This file contains routes and HTTP plumbing only: all portal knowledge lives
in client.py, all response shapes in models.py, all configuration in config.py.

Endpoints
---------
  GET /healthz                       liveness (never touches the portal)
  GET /api/v1/meters                 list/search, paginated (q, page)
  GET /api/v1/meters/{id}            detail: nameplate, hierarchy, location
  GET /api/v1/meters/{id}/consumption  30-min energy history (from, to)
  GET /api/v1/transformers           distribution-transformer list (page)
  GET /docs, GET /openapi.json       generated by FastAPI

Error mapping (no stack traces, no credentials, ever):
  404  portal says the meter/resource does not exist
  422  our own parameter validation (bad date, page < 1, ...)
  502  portal unreachable / rejected our session / returned junk
  504  portal timed out
  500  unexpected bug on our side (generic message; details go to logs)
"""

import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI, HTTPException, Query, Request
from fastapi.responses import HTMLResponse, JSONResponse

from .client import (
    PortalClient,
    PortalError,
    PortalNotFoundError,
    PortalTimeoutError,
)
from .config import settings
from .dashboard import DASHBOARD_HTML
from .models import (
    ConsumptionResponse,
    ErrorResponse,
    MeterDetailResponse,
    MeterListResponse,
    MeterQueryResponse,
    NearbyMetersResponse,
    NetworkHierarchyResponse,
    NetworkStatsResponse,
    TransformerListResponse,
    parse_api_date,
)

logger = logging.getLogger(__name__)

DESCRIPTION = """\
Read-only REST wrapper around the legacy "Urja Meter Ops" portal.

Every response mirrors the portal's own field names (see PROTOCOL.md for the
verified protocol) and adds a `warnings` array where portal data was messy.

All upstream failures are mapped: 404 (unknown meter), 502 (portal failed),
504 (portal timeout). Credentials and stack traces are never exposed.
"""

ERROR_RESPONSES = {
    404: {"model": ErrorResponse, "description": "Resource not found on the portal"},
    502: {"model": ErrorResponse, "description": "Portal failed or returned an unusable response"},
    504: {"model": ErrorResponse, "description": "Portal timed out"},
}


@asynccontextmanager
async def lifespan(app: FastAPI):
    # One shared client = one shared session + one shared re-login lock.
    portal = PortalClient(settings)
    app.state.portal = portal
    try:
        yield
    finally:
        await portal.aclose()  # close what we created, even if state was swapped


app = FastAPI(
    title="Urja Meter Ops REST API",
    description=DESCRIPTION,
    version="1.0.0",
    lifespan=lifespan,
)


# --------------------------------------------------------------------------
# Error handling
# --------------------------------------------------------------------------


@app.exception_handler(PortalError)
async def portal_error_handler(request: Request, exc: PortalError) -> JSONResponse:
    """Portal failures -> 404/502/504 with a safe, generic-ish message.

    exc.message is built by client.py and never contains credentials,
    portal HTML, or stack traces.
    """
    logger.warning("portal error on %s %s: %s", request.method, request.url.path, exc.message)
    return JSONResponse(status_code=exc.status_code, content={"detail": exc.message})


@app.exception_handler(Exception)
async def unhandled_error_handler(request: Request, exc: Exception) -> JSONResponse:
    """Last line of defence: log the traceback server-side, never send it out."""
    logger.exception("unhandled error on %s %s", request.method, request.url.path)
    return JSONResponse(status_code=500, content={"detail": "internal server error"})


