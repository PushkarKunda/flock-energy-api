@app.get(
    "/api/v1/meters/{meter_id}/consumption",
    response_model=ConsumptionResponse,
    responses=ERROR_RESPONSES,
    tags=["meters"],
    summary="30-minute energy history for one meter",
)
async def get_consumption(
    request: Request,
    meter_id: str,
    from_: str | None = Query(
        None, alias="from",
        description="Start date, inclusive: YYYY-MM-DD (or DD/MM/YYYY)",
    ),
    to: str | None = Query(
        None, description="End date, inclusive: YYYY-MM-DD (or DD/MM/YYYY)",
    ),
) -> ConsumptionResponse:
    from_date = _parse_date(from_)
    to_date = _parse_date(to)
    if from_date and to_date and from_date > to_date:
        raise HTTPException(status_code=422, detail="'from' must not be after 'to'")
    # Without a window the portal returns its default 7-day window (verified).
    return await request.app.state.portal.get_consumption(
        meter_id, from_date=from_date, to_date=to_date
    )


