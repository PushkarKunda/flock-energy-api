@app.get(
    "/api/v1/meters",
    response_model=MeterListResponse,
    responses=ERROR_RESPONSES,
    tags=["meters"],
    summary="List/search meters (portal: 20 rows per page)",
)
async def list_meters(
    request: Request,
    q: str = Query("", description="Matches meter number or serial (verified)"),
    page: int = Query(1, ge=1, description="1-based page number"),
) -> MeterListResponse:
    # Note: the portal silently treats page=0 / page=abc as page 1; we refuse
    # them instead (422) - documented in README "design decisions".
    return await request.app.state.portal.list_meters(q=q, page=page)


