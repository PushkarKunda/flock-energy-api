@app.get(
    "/api/v1/transformers",
    response_model=TransformerListResponse,
    responses=ERROR_RESPONSES,
    tags=["transformers"],
    summary="List distribution transformers (portal: 20 rows per page)",
)
async def list_transformers(
    request: Request,
    page: int = Query(1, ge=1, description="1-based page number"),
) -> TransformerListResponse:
    return await request.app.state.portal.list_transformers(page=page)


def _parse_date(value: str | None):
    """Convert an optional date parameter, 422 on anything we don't accept."""
    if value is None:
        return None
    try:
        return parse_api_date(value)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from None
